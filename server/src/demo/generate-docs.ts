/**
 * Writes the fictional demo documents (PDF) and illustrations (SVG) to client/public/demo-docs/<slug>/.
 * Output is deterministic for a given DEMO_ANCHOR, so re-running produces identical files.
 */
import fs from 'fs';
import path from 'path';
import { buildDemo, resolveAnchor } from './build';
import { demoDocuments } from './documents';

const root = path.resolve(__dirname, '..', '..', '..', 'client', 'public', 'demo-docs');
const data = buildDemo(resolveAnchor(process.env.DEMO_ANCHOR));
let total = 0;
for (const b of data.bundles) {
  const dir = path.join(root, b.def.slug);
  fs.rmSync(dir, { recursive: true, force: true });
  const { files } = demoDocuments(data, b);
  for (const f of files) {
    const out = path.join(dir, f.path);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, f.buffer);
  }
  total += files.length;
  console.log(`${b.def.name}: ${files.length} files`);
}
fs.writeFileSync(path.join(root, 'README.txt'),
  'FICTIONAL DEMONSTRATION MATERIAL\r\n\r\nEvery document and illustration in this folder was generated by server/src/demo (npm run demo:docs).\r\n' +
  'Projects, companies, people, figures, permits and approvals are fictional. Not for construction, contractual or legal use.\r\n');
console.log(`Wrote ${total} files to ${root}`);
